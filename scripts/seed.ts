async function main() {
  console.log("🌱 شروع سید بانک اطلاعاتی طوقی...");

  await db.delete(messages);
  await db.delete(conversations);
  await db.delete(favorites);
  await db.delete(listings);
  await db.delete(otpCodes);
  await db.delete(sessions);
  await db.delete(users);
  await db.delete(categories);
  await db.delete(cities);
  console.log("🧹 جداول قبلی پاک‌سازی شد");

  const cityRows = await db.insert(cities).values(CITIES.map((c) => ({
    name: c.name,
    slug: c.slug,
    featured: c.featured ?? false,
  }))).returning();
  const cityId = new Map<string, number>();
  cityRows.forEach((c) => {
    cityId.set(c.slug, c.id);
    cityId.set(c.name, c.id);
  });

  const catRows = await db.insert(categories).values(CATEGORIES).returning();
  const catId = new Map(catRows.map((c) => [c.slug, c.id]));

  const userRows: { id: string }[] = [];
  for (const u of USERS) {
    const [row] = await db
      .insert(users)
      .values({
        phone: u.phone,
        name: u.name,
        shop: u.shop,
        city: u.city,
        verified: u.verified,
        createdAt: new Date(Date.now() - u.daysAgo * 86400000),
      })
      .returning({ id: users.id });
    userRows.push(row);
  }
  console.log(`👥 ${userRows.length} کاربر ساخته شد`);

  let count = 0;
  for (const ad of ADS) {
    const jitter = Math.random();
    await db.insert(listings).values({
      id: randomUUID(),
      userId: userRows[ad.u].id,
      categoryId: catId.get(ad.cat)!,
      cityId: cityId.get(ad.city)!,
      title: ad.t,
      description: ad.d,
      price: ad.price,
      negotiable: ad.neg ?? false,
      images: ad.imgs.map(px),
      attributes: ad.a,
      status: ad.status ?? "active",
      featured: ad.feat ?? false,
      views: ad.views,
      createdAt: new Date(Date.now() - ad.days * 86400000 - jitter * 3600000),
    });
    count++;
  }
  console.log(`📢 ${count} آگهی ثبت شد`);
  console.log("✅ سید کامل شد.");
  await pool.end();
}

